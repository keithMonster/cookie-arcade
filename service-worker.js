async function precache() {
  const existed = await caches.has(CACHE_NAME);
  const cache = await caches.open(CACHE_NAME);
  const base = new URL(self.registration.scope);
  const abort = new AbortController();
  const oldNames = (await caches.keys()).filter(name => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME).reverse();
  const sources = await Promise.all(oldNames.map(name => caches.open(name)));
  if (existed) sources.unshift(cache);
  const requests = PRECACHE_PATHS.map(
    (path) => new Request(new URL(path, base), { cache: "reload", signal: abort.signal }),
  );
  // 后台安装不要一次挤满全部媒体请求，给正在玩的游戏留下带宽。
  let next = 0;
  const checkCanceled = () => { if (abort.signal.aborted) throw Error('install canceled'); };
  async function matches(response, hash) {
    if (!response?.ok) return false;
    const digest = await crypto.subtle.digest('SHA-256', await response.clone().arrayBuffer());
    return Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, '0')).join('') === hash;
  }
  async function prepare(index) {
    const request = requests[index], hash = PRECACHE_HASHES[PRECACHE_PATHS[index]];
    if (!hash) throw Error('missing asset hash');
    for (const source of sources) {
      const cached = await source.match(request, { ignoreVary: true });
      const valid = await matches(cached, hash);
      checkCanceled();
      if (!valid) continue;
      if (source !== cache) await cache.put(request, cached);
      checkCanceled();
      installProgress.reused++;
      return;
    }
    const response = await fetch(request);
    if (!await matches(response, hash)) throw Error('asset content mismatch');
    checkCanceled();
    await cache.put(request, response);
    checkCanceled();
    installProgress.downloaded++;
  }
  async function download() {
    while (next < requests.length && !abort.signal.aborted) {
      const timer = setTimeout(() => abort.abort(), 20000);
      try {
        await prepare(next++);
        installProgress.completed++;
      } catch (error) {
        // 任一请求失败就停其余队列；等全部写入退出后才清理新缓存。
        abort.abort();
        throw error;
      } finally {
        clearTimeout(timer);
      }
    }
  }
  const results = await Promise.allSettled(Array.from({ length: 4 }, download));
  const failure = results.find(result => result.status === 'rejected');
  if (failure || abort.signal.aborted || installProgress.completed !== requests.length) {
    // 只清本次新建缓存，避免 SW-only 更新误删仍在服务旧页面的同名缓存。
    if (!existed) await caches.delete(CACHE_NAME);
    throw failure?.reason || Error('incomplete offline cache');
  }
}

async function rangeResponse(request, response) {
  const match = /^bytes=(\d*)-(\d*)$/i.exec(request.headers.get("range") || "");
  if (!match) return response;

  const body = await response.arrayBuffer();
  const size = body.byteLength;
  if (size === 0) return response;

  let start;
  let end;
  if (match[1] === "") {
    const suffixLength = Number(match[2]);
    if (!Number.isFinite(suffixLength) || suffixLength <= 0) return response;
    start = Math.max(size - suffixLength, 0);
    end = size - 1;
  } else {
    start = Number(match[1]);
    end = match[2] === "" ? size - 1 : Number(match[2]);
  }

  if (
    !Number.isFinite(start) ||
    !Number.isFinite(end) ||
    start < 0 ||
    start >= size ||
    end < start
  ) {
    return new Response(null, {
      status: 416,
      headers: { "Content-Range": `bytes */${size}` },
    });
  }

  end = Math.min(end, size - 1);
  const headers = new Headers(response.headers);
  headers.set("Accept-Ranges", "bytes");
  headers.set("Content-Range", `bytes ${start}-${end}/${size}`);
  headers.set("Content-Length", String(end - start + 1));

  return new Response(body.slice(start, end + 1), {
    status: 206,
    statusText: "Partial Content",
    headers,
  });
}

self.addEventListener("install", (event) => {
  event.waitUntil(precache().then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(
        names
          .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
          .map((name) => caches.delete(name)),
      );
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE_NAME);
      const cached = await cache.match(request, { ignoreVary: true });
      if (cached) {
        return request.headers.has("range")
          ? rangeResponse(request, cached)
          : cached;
      }

      try {
        return await fetch(request);
      } catch (error) {
        if (request.mode === "navigate") {
          const fallback = await cache.match(
            new URL("./index.html", self.registration.scope),
          );
          if (fallback) return fallback;
        }
        throw error;
      }
    })(),
  );
});
